import assert from 'node:assert/strict';
import { mascotPose, mascotSegment, mascotFrame } from './mascot-motion.ts';
const angles=[Math.PI,Math.PI,0,0,-Math.PI/2,-Math.PI/2,-Math.PI/2,-Math.PI/2];
const rig=mascotPose(angles),before=rig.map(q=>[...q]);
const left=mascotSegment(rig,13,15),right=mascotSegment(rig,14,16);
assert.ok(left.visible&&right.visible);assert.ok(left.x<rig[13][0],'screen-left arm reaches left');
rig[15]=[rig[13][0],rig[13][1]+1,1];
assert.notEqual(mascotSegment(rig,13,15).angle,left.angle,'wrist update changes its forearm immediately');
assert.deepEqual(mascotSegment(rig,14,16),right,'opposite arm is independent');
const up=mascotSegment(rig,13,15);assert.ok(up.y<left.y,'raised wrist renders above shoulder in SVG');
assert.equal(mascotFrame(rig).visible,true);rig[11][2]=0;assert.equal(mascotFrame(rig).visible,false,'lost torso cannot show a fabricated body');
assert.equal(mascotSegment(rig,11,13).visible,false);rig[11]=[NaN,0,1];assert.equal(mascotSegment(rig,11,13).visible,false);
assert.deepEqual(mascotPose(angles),before,'target posing is deterministic and does not mutate its angles');
assert.equal(mascotSegment([],11,13).visible,false);
console.log('Mascot rig: immediate independent limbs, camera orientation, target poses and missing-joint hiding pass.');
const { mascotDisplayRig }=await import('./mascot-motion.ts');
const upper=mascotPose(angles);for(const j of [23,24,25,26,27,28])upper[j][2]=0;const realArm=[...upper[15]];
const fallback=mascotDisplayRig(upper);assert.equal(mascotFrame(fallback).visible,true,'valid upper-body play keeps a neutral display torso');assert.deepEqual(fallback[15],realArm,'fallback never changes tracked arms');assert.equal(upper[23][2],0,'fallback never changes tracker/input data');
upper[11][2]=upper[12][2]=0;assert.equal(mascotFrame(mascotDisplayRig(upper)).visible,false,'missing shoulders still hide puppet');

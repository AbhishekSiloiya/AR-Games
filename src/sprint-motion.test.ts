import assert from 'node:assert/strict';
import { sprintMotion } from './sprint-motion.ts';
import { sprintCanVault } from './sprint-motion.ts';
const rig=Array.from({length:33},()=>[0,0,1,0,0]);
rig[23][1]=rig[24][1]=-1;rig[25][1]=rig[26][1]=-2;
const motion=sprintMotion();
assert.equal(motion(rig,0).steps,0,'standing cannot score');
rig[25][1]=-1.97;
assert.ok(motion(rig,.03).left>0,'the first visible knee movement changes the robot pose immediately');
rig[25][1]=-1.4;
let frame=motion(rig,.06);
assert.equal(frame.steps,1,'the first lifted knee counts immediately');
assert.ok(frame.cadence>0,'first step has pace without waiting for the opposite knee');
assert.ok(frame.left>.6&&frame.right===0,'left leg responds independently');
assert.equal(motion(rig,.08).steps,0,'repeated tracking/render frames cannot award another step');
rig[25][1]=-2;rig[26][1]=-1.4;
frame=motion(rig,.15);
assert.equal(frame.steps,1,'opposite knee fires on its own next update');
assert.ok(frame.right>.6&&frame.left===0,'the robot copies the opposite knee without finishing a canned cycle');
frame=motion(rig,.35);
assert.equal(frame.cadence,0,'stopping/holding a knee still stops pace within 200 ms');
assert.equal(frame.steps,0,'holding a raised leg cannot score');
frame=motion([], .4);
assert.equal(frame.left+frame.right+frame.steps+frame.cadence,0,'absence clears pose, speed and scoring');
assert.equal(motion(rig,.45).steps,0,'reacquiring an already raised leg cannot award a step');
rig[26][1]=-2;motion(rig,.5);rig[26][1]=-1.4;
assert.equal(motion(rig,.6).steps,1,'a deliberate new lift after reacquisition counts');
frame=motion(rig,.65,false);
assert.equal(frame.steps+frame.cadence,0,'rest and countdown never award movement');
for(let i=1;i<=60;i++)assert.equal(motion(rig,.65+i/60,false).steps,0,'idle/rest cannot create free steps');
console.log('Sprint motion: immediate first/opposite knee, repeated frames, fast stop, absence, reacquisition and rest pass.');
const raised=[{seen:true,y:.9},{seen:true,y:.9}];
assert.equal(sprintCanVault(false,true,rig,raised),false,'absent player cannot clear with cached jump/hands');
assert.equal(sprintCanVault(true,false,rig,raised),true,'both visible raised hands can vault');
assert.equal(sprintCanVault(true,true,rig,raised.map(h=>({...h,seen:false}))),true,'visible legs can jump');
rig[27][2]=0;
assert.equal(sprintCanVault(true,true,rig,raised.map(h=>({...h,seen:false}))),false,'missing legs cannot bank a cached jump');

import assert from 'node:assert/strict';
const module=await import('./round-lifetime.ts').catch(()=>null);
assert.ok(module,'round cleanup must support resources that finish loading after the round closes');
const {roundLifetime}=module;
const first=roundLifetime(),second=roundLifetime(),events:string[]=[];
first.add(()=>events.push('first effect'));
second.add(()=>events.push('second effect'));
first.close();
first.add(()=>events.push('late first asset'));
assert.deepEqual(events,['first effect','late first asset'],'late cleanup runs immediately, rather than leaking into the next round');
assert.equal(first.closed,true);
assert.equal(second.closed,false);
first.close();
assert.deepEqual(events,['first effect','late first asset'],'teardown is idempotent');
second.close();
assert.deepEqual(events,['first effect','late first asset','second effect'],'old teardown never drains the current round');
const nested=roundLifetime();let calls=0;
nested.add(()=>{calls++;nested.add(()=>calls++);nested.close();});nested.close();assert.equal(calls,2,'cleanup registered during teardown is drained exactly once');
console.log('Round lifetime: late and nested cleanup runs once, isolated from the next round.');

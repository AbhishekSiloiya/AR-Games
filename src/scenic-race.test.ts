import assert from 'node:assert/strict';
import { jogDetector, raceState, raceAdvance, raceMedal } from './scenic-race.ts';
const standing=()=>{const r=Array.from({length:33},()=>[0,0,1,0,0]);r[23][1]=r[24][1]=-1;r[25][1]=r[26][1]=-2;r[15][1]=r[16][1]=-.8;return r;};
let rig=standing();const jog=jogDetector();
assert.equal(jog(rig,0,1,true,.3,.2).beat,0);
rig[25][1]=-1.6;let m=jog(rig,.1,2,true,.3,.2);
assert.equal(m.beat,1,'first forgiving knee lift starts immediately');assert.ok(m.pace>0);
assert.equal(jog(rig,.2,2,true,.3,.2).beat,1,'repeated source frame cannot invent a step');
assert.equal(jog(rig,.4,3,true,.3,.2).beat,1,'held high knee cannot repeat');
assert.equal(jog(rig,1.2,4,true,.3,.2).pace,0,'cadence stops after a short natural hold');
assert.equal(jog(rig,1.3,5,false,.3,.2).pace,0,'absence clears pace');
assert.equal(jog(rig,1.4,6,true,.3,.2).beat,1,'reacquiring raised leg cannot count');
rig=standing();const arms=jogDetector();arms(rig,0,1,true,.3,.2);rig[15][1]=-.45;
assert.equal(arms(rig,.2,2,true,.3,.2).beat,1,'arm pump fallback counts without high knees');
rig[15][1]=-.8;arms(rig,.4,3,true,.3,.2);rig[15][1]=-.45;
assert.equal(arms(rig,.6,4,true,.3,.2).beat,1,'same arm alone cannot pretend to alternate');
rig[16][1]=-.45;assert.equal(arms(rig,.8,5,true,.3,.2).beat,2,'opposite arm pump counts');
const noise=jogDetector();rig=standing();noise(rig,0,1,true,.3,.2);
for(let i=1;i<120;i++){rig[25][1]=-2+(i%2)*.02;rig[15][1]=-.8+(i%2)*.025;assert.equal(noise(rig,i/30,i+1,true,.3+(i%2)*.001,.2).beat,0,'tracker noise cannot score');}
const bob=jogDetector();rig=standing();bob(rig,0,1,true,.3,.2);
assert.equal(bob(rig,.2,2,true,.27,.2).beat,1,'visible body bounce is a forgiving fallback');
assert.equal(bob(rig,.4,3,true,.27,.2).beat,1,'held body shift cannot repeat');
let race=raceState();for(let i=0;i<90;i++)race=raceAdvance(race,0,1/60);
assert.equal(race.metres+race.stars,0,'ambient animation and time earn nothing');
for(let beat=1;beat<=9;beat++)race=raceAdvance(race,beat,.1);
assert.equal(race.stars,3);assert.equal(race.boosts,1);assert.ok(race.boost>0,'three earned stars activate turbo');
const before=race.metres;race=raceAdvance(race,9,.1);assert.equal(race.metres,before,'same detected beat rewards once');
race=raceAdvance(race,10,.1);assert.ok(race.metres-before>2.2,'turbo amplifies earned movement');
assert.equal(raceMedal(0),'Explorer');assert.equal(raceMedal(45),'Bronze');assert.equal(raceMedal(85),'Silver');assert.equal(raceMedal(125),'Gold');
console.log('Scenic race: knee/arm/body starts, held/noisy/repeated/absent inputs, movement-only stars, once-only turbo and medals pass.');
const chargeTestStart=raceState();let charging=chargeTestStart;
for(let beat=1;charging.boost===0;beat++)charging=raceAdvance(charging,beat,.1);
const firstBoosts=charging.boosts,firstTimer=charging.boost;
for(let i=0;i<15;i++)charging=raceAdvance(charging,charging.lastBeat+1,.1);
assert.equal(charging.boosts,firstBoosts,'stars during turbo cannot continually refresh turbo');
assert.ok(charging.boost<firstTimer,'turbo must run down even while collecting stars');

import assert from 'node:assert/strict';
import { armShooter } from './arm-shot.ts';
const rig=Array.from({length:33},()=>[0,0,1,0,0]);
rig[11]=[-.5,0,1];rig[12]=[.5,0,1];rig[15]=[-1,-.5,1];rig[16]=[1,-.5,1];
const shoot=armShooter();
assert.equal(shoot(rig,0).length,0);
rig[15]=[-1,.6,1]; const shots=shoot(rig,.3);
assert.equal(shots.length,1,'raising either hand fires without feet or other hand');
assert.ok(shots[0].dx<0 && shots[0].dy>0,'left hand aims to upper left');
assert.equal(shoot(rig,.7).length,0,'held arm cannot repeat');
rig[15][1]=-.3;shoot(rig,.8);rig[15][1]=.6;
assert.equal(shoot(rig,1.1).length,1,'lowering rearms');
rig[16]=[1,.6,1];assert.equal(shoot(rig,1.2).length,1,'hands work independently');
rig[15][2]=0;shoot(rig,1.3);rig[15][2]=1;
assert.equal(shoot(rig,1.7).length,0,'reacquiring raised hand cannot fire');
const entering=armShooter();assert.equal(entering(rig,0).length,0,'entering with hands high cannot fire');
